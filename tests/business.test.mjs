import { JSDOM } from 'jsdom';
import { createServer } from 'vite';
import assert from 'node:assert/strict';
const dom = new JSDOM('<!doctype html><html><body></body></html>', { url: 'http://localhost:3001' });
Object.assign(globalThis, { window: dom.window, document: dom.window.document, HTMLElement: dom.window.HTMLElement, MutationObserver: dom.window.MutationObserver, FormData: dom.window.FormData, IS_REACT_ACT_ENVIRONMENT: true });
Object.defineProperty(globalThis, 'navigator', { value: dom.window.navigator, configurable: true });
const React = await import('react');
const { render, fireEvent, cleanup, waitFor, screen } = await import('@testing-library/react');
const server = await createServer({ server: { middlewareMode: true, watch: null, hmr: false }, optimizeDeps: { noDiscovery: true, include: [] }, appType: 'custom' });
let testSupabase;
try {
  ({ supabase: testSupabase } = await server.ssrLoadModule('/src/lib/supabase.ts'));
  const { retail } = await server.ssrLoadModule('/src/features/retail/api.ts');
  const { productsForList, salesCsv } = await server.ssrLoadModule('/src/features/retail/pricing.ts');
  const { BranchSettings, PriceListSettings, LedgerSettings } = await server.ssrLoadModule('/src/features/retail/BusinessSettings.tsx');
  const { SalesOverview } = await server.ssrLoadModule('/src/features/retail/SalesOverview.tsx');
  const products = [{ id: 'p', name: 'Agua', code: 'AGUA', price: 100.05, stock: 5, categoryId: 'c', category: 'Bebidas', active: true }];
  const lists = [{ id: 'l', name: 'Mayorista', adjustment: -10, active: true }];
  assert.equal(productsForList(products, undefined, [])[0].price, 100.05);
  assert.equal(productsForList(products, lists[0], [])[0].price, 90.05);
  assert.equal(productsForList(products, lists[0], [{ list_id: 'l', product_id: 'p', price: 80 }])[0].price, 80);
  assert.equal(products[0].price, 100.05);
  assert.equal(productsForList([{ ...products[0], price: 0.01 }], { ...lists[0], adjustment: -99.99 }, [])[0].price, 0.01);
  console.log('PASS mother price, decimal rounding, overrides and immutable input');
  const calls = [];
  const run = async action => { await action(); return true; };
  retail.saveBranch = async (...args) => calls.push(args);
  render(React.createElement(BranchSettings, { storeId: 's', branches: [], run, busy: false }));
  fireEvent.change(screen.getByLabelText('Nueva sucursal'), { target: { value: 'Centro' } });
  fireEvent.change(screen.getByLabelText('Dirección'), { target: { value: 'San Martín 100' } });
  await React.act(async () => fireEvent.submit(document.querySelector('form')));
  assert.deepEqual(calls.pop(), ['s', 'Centro', 'San Martín 100', undefined]);
  cleanup();
  console.log('PASS creating a branch submits the location within its store');
  retail.savePriceList = async (...args) => calls.push(args);
  retail.savePriceOverride = async (...args) => calls.push(args);
  render(React.createElement(PriceListSettings, { storeId: 's', lists, overrides: [{ list_id: 'l', product_id: 'p', price: 80 }], products, run, busy: false }));
  fireEvent.click(screen.getByText('Listas de precios · Ver y administrar'));
  fireEvent.change(screen.getByLabelText('Consultar lista'), { target: { value: 'l' } });
  const fixed = screen.getByLabelText('Precio fijo de Agua');
  assert.equal(fixed.value, '80');
  fireEvent.change(fixed, { target: { value: '' } });
  await React.act(async () => fireEvent.submit(fixed.closest('form')));
  assert.deepEqual(calls.pop(), ['s', 'l', 'p', null]);
  cleanup();
  console.log('PASS empty override restores the derived price');
  render(React.createElement(LedgerSettings, { storeId: 's', ledgers: [{ id: 'general', name: 'General', is_default: true, active: true }], run, busy: false }));
  assert.equal(screen.queryByText('Desactivar'), null);
  cleanup();
  console.log('PASS default ledger cannot be deactivated in settings');
  const rows = [
    { id: 'sale1', ticketNumber: 'T-1', branchId: 'b1', branchName: 'Centro', registerName: 'Caja 1', ledgerId: 'general', ledgerName: 'General', priceListName: 'Lista madre', total: 100, invoiceReference: 'Factura A 1', createdAt: '2026-10-13T15:00:00Z', items: [] },
    { id: 'sale2', ticketNumber: 'T-2', branchId: 'b2', branchName: 'Norte', registerName: 'Caja 1', ledgerId: 'other', ledgerName: '=danger()', priceListName: 'Mayorista', total: 50, invoiceReference: null, createdAt: '2026-10-13T16:00:00Z', items: [] },
  ];
  retail.reportSales = async (...args) => { calls.push(args); return rows; };
  retail.attachInvoice = async (...args) => calls.push(args);
  render(React.createElement(SalesOverview, { storeId: 's', branches: [{ id: 'b1', name: 'Centro' }, { id: 'b2', name: 'Norte' }], registers: [], shifts: [], ledgers: [{ id: 'general', name: 'General' }, { id: 'other', name: 'Otras' }], revision: 0, run, busy: false, onTicket: () => {} }));
  await waitFor(() => assert.ok(screen.getByText('T-2')));
  fireEvent.change(screen.getByLabelText('Sucursal del informe'), { target: { value: 'b2' } });
  assert.equal(screen.queryByText('T-1'), null);
  assert.ok(screen.getByText('T-2'));
  fireEvent.click(screen.getByText('Sin comprobante · Asociar'));
  const ref = screen.getByLabelText('Referencia del comprobante ya emitido');
  fireEvent.change(ref, { target: { value: 'Factura B 2' } });
  await React.act(async () => fireEvent.submit(ref.closest('form')));
  assert.deepEqual(calls.pop(), ['sale2', 'Factura B 2']);
  let exported;
  const oldCreate = URL.createObjectURL;
  URL.createObjectURL = blob => { exported = blob; return 'blob:test'; };
  const oldClick = dom.window.HTMLAnchorElement.prototype.click;
  dom.window.HTMLAnchorElement.prototype.click = () => {};
  fireEvent.click(screen.getByText('Exportar período completo (CSV)'));
  const csv = await exported.text();
  assert.ok(csv.includes('T-1') && csv.includes('T-2'));
  assert.ok(csv.includes("'=danger()"));
  assert.ok(salesCsv(rows).includes('Sin comprobante asociado'));
  URL.createObjectURL = oldCreate;
  dom.window.HTMLAnchorElement.prototype.click = oldClick;
  cleanup();
  console.log('PASS report filtering, invoice association and complete CSV export with formula protection');
} finally { cleanup(); await testSupabase?.auth.dispose(); await server.close(); dom.window.close(); }
