import { PGlite } from '@electric-sql/pglite';
import { readFile, readdir } from 'node:fs/promises';
import assert from 'node:assert/strict';
const db = new PGlite();
const scalar = async (q, p = []) => Object.values((await db.query(q, p)).rows[0])[0];
const owner = crypto.randomUUID(), stranger = crypto.randomUUID();
const login = async id => { await db.exec('reset role'); await db.query("select set_config('request.jwt.claim.sub',$1,false)", [id]); await db.exec('set role authenticated'); };
const sync = operation => scalar('select retail_sync_operation($1)', [JSON.stringify(operation)]);
try {
  await db.exec(`create role anon; create role authenticated; create role service_role bypassrls; create schema auth;
    create table auth.users(id uuid primary key,email text,email_confirmed_at timestamptz);
    create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
    grant usage on schema auth to authenticated; grant execute on function auth.uid() to authenticated;`);
  for (const file of (await readdir('supabase/migrations')).filter(f => f.endsWith('.sql')).sort()) await db.exec((await readFile(`supabase/migrations/${file}`, 'utf8')).replace(/^\uFEFF/, ''));
  for (const id of [owner, stranger]) await db.query('insert into auth.users values($1,$2,now())', [id, `${id}@example.test`]);
  await login(owner);
  const store = await scalar("select retail_create_store('Offline shop')");
  const register = await scalar('select id from retail_registers where store_id=$1', [store]);
  const branch = await scalar('select branch_id from retail_registers where id=$1', [register]);
  const category = await scalar('select id from retail_categories where store_id=$1 limit 1', [store]);
  const product = await scalar("insert into retail_products(store_id,category_id,name,code,price,stock) values($1,$2,'Café','CAFE',100,10) returning id", [store, category]);
  await db.query('select retail_save_quick_products($1,$2,$3)', [store, branch, [product]]);
  assert.equal(await scalar('select product_id from retail_quick_products'), product);
  await assert.rejects(() => db.query('select retail_save_quick_products($1,$2,$3)', [store, branch, [product, product]]), /20 productos/);
  await assert.rejects(() => db.query('select retail_save_quick_products($1,$2,$3)', [store, branch, [crypto.randomUUID()]]), /20 productos/);
  const open = { id: crypto.randomUUID(), kind: 'open', store, register, at: new Date(Date.now() - 60000).toISOString(), amount: 100 };
  await sync(open); await sync(open);
  assert.equal(await scalar('select count(*) from retail_shifts'), 1);
  const sale = { id: crypto.randomUUID(), kind: 'sale', store, shift: open.id, at: new Date(Date.now() - 30000).toISOString(), method: 'Mixto', paid: 200, items: [{ product_id: product, qty: 2, unit_price: 100 }], payments: [{ method: 'Efectivo', amount: 70 }, { method: 'Transferencia', amount: 130 }], priceList: null, ledger: null };
  const receipt = await sync(sale); assert.match(receipt.ticketNumber, /^T-/);
  await sync(sale); assert.equal(await scalar('select stock from retail_products where id=$1', [product]), 8);
  assert.equal(Number(await scalar('select cash_amount from retail_sales where id=$1', [sale.id])), 70);
  await assert.rejects(() => sync({ ...sale, paid: 300 }), /otra operación/);
  const broken = { ...sale, id: crypto.randomUUID(), payments: [{ method: 'Efectivo', amount: 100 }, { method: 'QR', amount: 130 }] };
  await assert.rejects(() => sync(broken), /desglose/);
  assert.equal(await scalar('select stock from retail_products where id=$1', [product]), 8, 'invalid split rolls back stock');
  const movement = { id: crypto.randomUUID(), kind: 'movement', store, shift: open.id, type: 'RETIRO', amount: 20, reason: 'Proveedor', at: new Date().toISOString() };
  await sync(movement); await sync(movement);
  assert.equal(Number(await scalar('select retail_shift_balance($1)', [open.id])), 150);
  const close = { id: crypto.randomUUID(), kind: 'close', store, shift: open.id, amount: 150, at: new Date().toISOString() };
  assert.equal((await sync(close)).expected, 150); await sync(close);
  assert.equal((await sync(sale)).ticketNumber, receipt.ticketNumber, 'retry after closure is safe');
  assert.equal(await scalar('select count(*) from retail_sales'), 1);
  assert.equal(Number((await db.query('select * from retail_popular_products($1,$2)', [store, branch])).rows[0].units), 2);
  await db.query('update retail_products set stock=7 where id=$1', [product]);
  const stockOperation = { id: crypto.randomUUID(), kind: 'stock', store, at: new Date().toISOString(), items: [{ product, delta: 5, cost: 40 }] };
  await sync(stockOperation); await sync(stockOperation);
  assert.equal(await scalar('select stock from retail_products where id=$1', [product]), 12);
  assert.equal(await scalar('select count(*) from retail_stock_movements'), 1);
  await assert.rejects(() => sync({ ...stockOperation, id: crypto.randomUUID(), items: [{ product, delta: -100, cost: null }] }), /Stock resultante/);
  assert.equal(await scalar('select stock from retail_products where id=$1', [product]), 12);
  await login(stranger);
  await assert.rejects(() => sync(sale), /Sin acceso/);
  await assert.rejects(() => sync(stockOperation), /Sin acceso/);
  await assert.rejects(() => db.query('select retail_popular_products($1,$2)', [store, branch]), /Sin acceso/);
  await assert.rejects(() => db.query('select * from retail_sync_receipts'), /permission denied/);
  assert.equal(await scalar('select count(*) from retail_quick_products'), 0);
  console.log('PASS offline RPC ordering, idempotency including closed shifts, mixed cash reconciliation, atomic rollback, original timestamps, branch quick products and authorization');
} catch (error) { console.error('FAIL', error.message, error.query || ''); process.exitCode = 1; }
finally { await db.close(); }
